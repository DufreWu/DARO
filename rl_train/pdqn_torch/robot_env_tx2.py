    def get_reward(self, fps, e_d, target_fps, beta):
        u = max(1, fps / target_fps)

        if fps >= target_fps:
            u = 1
        else:
            u = (fps / target_fps)**3
        
        reward = (u + beta / e_d)
        print('get_reward()-fps = {}, e_d = {}, u = {}, reward = {}'.format(fps, e_d, u, reward))
        return reward

    def get_sim_current_state(self, c_c, g_c, speed):
        c_p = self.optical_flow_power[c_c][g_c] / 1000.0
        m_p = 1.14005 * speed + 0.108930 * speed * speed * speed + 1.1625
        fps = self.optical_flow_thr[c_c][g_c]
        fps = fps - (speed - 2.0)
        print('get_sim_current_state()-c_p = {}, m_p = {}, fps = {}'.format(c_p, m_p, fps))
        return c_c, g_c, c_p, m_p, fps

