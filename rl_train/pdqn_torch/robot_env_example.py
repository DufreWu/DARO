    def get_reward(self, fps, e_d, target_fps, beta):
        print('get_reward()-e_d = {}'.format(e_d))
        v1 = 0.2
        u = max(1, fps / target_fps)

        if fps >= target_fps:
            u = 1
        else:
            u = fps / target_fps
        return u + v1 + beta / e_d

